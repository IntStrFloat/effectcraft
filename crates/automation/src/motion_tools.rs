pub fn schema_empty() -> Value {
    json!({"type":"object","properties":{},"additionalProperties":false})
}

pub fn capabilities(b: &mut Backend, _: &Value) -> Result<Reply> {
    let app = b.exec("app.capabilities", json!({}))?;
    let project = b.exec("project.summary", json!({}))?;
    let plugins = b.exec("effect.plugins.list", json!({}))?;
    Ok(Reply::Json(json!({"app":app,"renderer":project.get("renderer"),"plugins":plugins,
        "automation":{"mode":if b.is_bridge(){"bridge"}else{"headless"},"starter_recipes":"motion_catalog",
            "new_scene_preserves_existing_comps":true,"high_level_key_time_base":"comp",
            "legacy_key_time_base":"layer unless timeBase=comp","actual_preview":"render_storyboard / render_frame",
            "workflow_resource":"effectcraft://workflow"},
        "compatibility":{"native_project":".ecproj","adobe_projects":false,"adobe_animation_presets":false,
            "adobe_sdk_plugins":false,"native_ofx_plugins":false,"own_plugin_api":"WebAssembly v1 (availability is reported in plugins.wasm)",
            "registry_is_not_fidelity_proof":true,"gpu_effect_badge_means":"additional GPU implementation, not CPU exclusion"},
        "limits":{"maturity":"alpha; validate each production shot","no_claim_of_after_effects_pixel_equivalence":true,
            "preview_max_frames":12,"preview_max_side":960,"preview_max_atlas_pixels":8_000_000}})))
}

