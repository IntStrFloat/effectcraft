pub fn load_plugin_schema() -> Value {
    json!({"type":"object","additionalProperties":false,"required":["path"],"properties":{
        "path":{"type":"string","description":"Absolute path to an EffectCraft API-v1 .wasm or .wat plugin. Read roots apply."}}})
}

pub fn load_plugin(b: &mut Backend, args: &Value) -> Result<Reply> {
    let path = args
        .get("path")
        .and_then(Value::as_str)
        .filter(|s| !s.is_empty() && s.len() <= 32768)
        .ok_or_else(|| Error::BadArgs("`path` must be a nonempty absolute file path".into()))?;
    let path_ref = std::path::Path::new(path);
    if !path_ref.is_absolute()
        || !path_ref.extension().and_then(|s| s.to_str()).is_some_and(|s| s.eq_ignore_ascii_case("wasm") || s.eq_ignore_ascii_case("wat"))
    {
        return Err(Error::BadArgs("give an absolute EffectCraft .wasm/.wat path; Adobe SDK/AEX and OFX plugins are not hosted".into()));
    }
    Ok(Reply::Json(b.exec("effect.plugins.load", json!({"path":path}))?))
}

