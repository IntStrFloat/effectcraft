pub fn chain_schema() -> Value {
    json!({"type":"object","additionalProperties":false,"required":["comp","layer","effects"],"properties":{
        "comp":{"type":["integer","string"],"description":"Explicit composition id or name."},
        "layer":{"type":["integer","string"],"description":"Explicit layer id, name or #n in that composition."},
        "mode":{"type":"string","enum":["append","replace"],"default":"append"},
        "effects":{"type":"array","maxItems":32,"items":{"type":"object","additionalProperties":false,"required":["effect"],"properties":{
            "effect":{"type":"string","description":"Exact registered effect id or name from list_effects."},
            "values":{"type":"object","description":"Parameter ids from list_effects to native values; unknown ids fail atomically."},
            "enabled":{"type":"boolean","default":true}}}}}})
}

fn reference<'a>(args: &'a Value, key: &str) -> Result<&'a Value> {
    let value = args.get(key).ok_or_else(|| Error::BadArgs(format!("`{key}` required")))?;
    if value.as_u64().is_some_and(|n| n > 0) || value.as_str().is_some_and(|s| !s.trim().is_empty() && s.len() <= 1024) {
        Ok(value)
    } else {
        Err(Error::BadArgs(format!("`{key}` must be a positive id or nonempty name")))
    }
}

fn effects_group(tree: &Value) -> Option<&Value> {
    tree.get("properties")?.get("children")?.as_array()?.iter().find(|group| group.get("path").and_then(Value::as_str) == Some("effects"))
}

fn literal_values(value: &Value) -> Result<()> {
    let mut pending = vec![value];
    let mut seen = 0usize;
    while let Some(value) = pending.pop() {
        seen += 1;
        if seen > 8192 {
            return Err(Error::BadArgs("effect values exceed the 8192-node input budget".into()));
        }
        match value {
            Value::String(text) => {
                if let Some(rest) = text.strip_prefix('$') {
                    let mut parts = rest.split('.');
                    let numeric = parts.next().is_some_and(|n| n.parse::<usize>().is_ok());
                    if numeric && parts.all(|p| !p.is_empty() && p.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')) {
                        return Err(Error::BadArgs("effect value looks like an engine.batch reference; set this exact literal afterwards with set_property instead of silently substituting it".into()));
                    }
                }
            }
            Value::Array(values) => {
                if values.len() > 8192usize.saturating_sub(seen.saturating_add(pending.len())) {
                    return Err(Error::BadArgs("effect values exceed the 8192-node input budget".into()));
                }
                pending.extend(values);
            }
            Value::Object(values) => {
                if values.len() > 8192usize.saturating_sub(seen.saturating_add(pending.len())) {
                    return Err(Error::BadArgs("effect values exceed the 8192-node input budget".into()));
                }
                pending.extend(values.values());
            }
            _ => {}
        }
    }
    Ok(())
}

pub fn chain(b: &mut Backend, args: &Value) -> Result<Reply> {
    let comp = reference(args, "comp")?;
    let layer = reference(args, "layer")?;
    let mode = match args.get("mode") {
        None => "append",
        Some(Value::String(mode)) if matches!(mode.as_str(), "append" | "replace") => mode,
        _ => return Err(Error::BadArgs("`mode` must be append or replace".into())),
    };
    let effects = args.get("effects").and_then(Value::as_array).ok_or_else(|| Error::BadArgs("`effects` must be an array".into()))?;
    if effects.len() > 32 {
        return Err(Error::BadArgs("at most 32 effects per chain".into()));
    }
    let before = b.exec("layer.tree", json!({"comp":comp,"layer":layer,"depth":2}))?;
    // User-visible names may themselves look like $N. Resolve targets before putting them
    // inside engine.batch, whose result-reference substitution is deliberately recursive.
    let comp_info = b.exec("comp.info", json!({"comp":comp}))?;
    let comp_id = comp_info.get("id").filter(|id| id.is_u64()).cloned().ok_or_else(|| Error::Other("composition returned no numeric id".into()))?;
    let layer_id = before.get("id").filter(|id| id.is_u64()).cloned().ok_or_else(|| Error::Other("layer returned no numeric id".into()))?;
    let (comp, layer) = (&comp_id, &layer_id);
    let existing = effects_group(&before)
        .and_then(|g| g.get("children"))
        .and_then(Value::as_array)
        .ok_or_else(|| Error::BadArgs("target layer has no effects group".into()))?
        .len();
    let catalog = b.exec("effect.list", json!({}))?;
    let catalog = catalog.as_array().ok_or_else(|| Error::Other("effect catalog returned no array".into()))?;
    let mut prepared = Vec::with_capacity(effects.len());
    for (index, effect) in effects.iter().enumerate() {
        let object = effect.as_object().ok_or_else(|| Error::BadArgs(format!("effects[{index}] must be an object")))?;
        if let Some(key) = object.keys().find(|key| !matches!(key.as_str(), "effect" | "values" | "enabled")) {
            return Err(Error::BadArgs(format!("unknown effect argument `{key}`")));
        }
        let name = object
            .get("effect")
            .and_then(Value::as_str)
            .filter(|name| !name.trim().is_empty())
            .ok_or_else(|| Error::BadArgs(format!("effects[{index}].effect required")))?;
        let definition = catalog
            .iter()
            .find(|entry| ["id", "name"].iter().any(|key| entry.get(key).and_then(Value::as_str).is_some_and(|s| s.eq_ignore_ascii_case(name))))
            .ok_or_else(|| Error::BadArgs(format!("unknown effect `{name}`; inspect list_effects / list_plugins")))?;
        let values = match object.get("values") {
            None => json!({}),
            Some(Value::Object(values)) if values.len() <= 256 => Value::Object(values.clone()),
            _ => return Err(Error::BadArgs("effect values must be an object of at most 256 parameters".into())),
        };
        literal_values(&values)?;
        for key in values.as_object().into_iter().flat_map(|values| values.keys()) {
            if !definition.get("params").and_then(Value::as_array).is_some_and(|params| params.iter().any(|p| p.get("id").and_then(Value::as_str) == Some(key)))
            {
                return Err(Error::BadArgs(format!("`{name}` has no parameter `{key}`; inspect list_effects")));
            }
        }
        let enabled =
            object.get("enabled").map(|v| v.as_bool().ok_or_else(|| Error::BadArgs("effect enabled must be boolean".into()))).transpose()?.unwrap_or(true);
        prepared.push((definition.get("id").cloned().ok_or_else(|| Error::Other("effect catalog entry has no id".into()))?, values, enabled));
    }
    let mut steps = Vec::new();
    if mode == "replace" {
        steps.push(json!({"command":"effect.removeAll","params":{"comp":comp,"layers":[layer]}}));
    }
    let first = if mode == "replace" { 1 } else { existing.saturating_add(1) };
    for (offset, (effect, values, enabled)) in prepared.iter().enumerate() {
        let index = first.saturating_add(offset);
        let apply_step = steps.len().saturating_add(1);
        steps.push(json!({"command":"effect.apply","params":{"comp":comp,"layers":[layer],"effect":effect}}));
        for (param, value) in values.as_object().into_iter().flat_map(|v| v.iter()) {
            steps.push(json!({"command":"prop.set","params":{"comp":comp,"layer":layer,"path":format!("effects/#{index}/{param}"),"value":value}}));
        }
        if !enabled {
            steps.push(json!({"command":"effect.toggle","params":{"comp":comp,"layer":layer,"effect":format!("${apply_step}.effects.0"),"value":false}}));
        }
    }
    if !steps.is_empty() {
        b.exec("engine.batch", json!({"steps":steps,"atomic":true,"label":"Apply Motion Effect Chain"}))?;
    }
    let after = b.exec("layer.tree", json!({"comp":comp,"layer":layer}))?;
    Ok(Reply::Json(json!({"comp":comp,"layer":after.get("id"),"mode":mode,"applied":prepared.len(),
        "first_index":first,"effects":effects_group(&after),
        "reference_notice":if mode=="replace" {"Removed effects and their keys have new identities; inspect expressions that referenced old effect UIDs."}else{"Existing effects remain before the appended chain."}})))
}

pub fn prompts() -> Value {
    json!({"prompts":[{"name":"motion_design","title":"Design and refine an editable motion scene",
        "description":"Turn a purpose/style/timing brief into an inspected, previewed and exported EffectCraft scene.",
        "arguments":[{"name":"brief","description":"Purpose, visual action, style, duration and sources in any language.","required":true},
            {"name":"context","description":"Existing project/comp/layer ids and constraints.","required":false},
            {"name":"output_path","description":"Optional delivery path; choose format/alpha/frame rate explicitly.","required":false}]}]})
}

pub fn prompt(params: &Value) -> Result<Value> {
    if params.get("name").and_then(Value::as_str) != Some("motion_design") {
        return Err(Error::BadArgs("unknown prompt; use motion_design".into()));
    }
    let args = params.get("arguments").and_then(Value::as_object).ok_or_else(|| Error::BadArgs("prompt arguments object required".into()))?;
    if args.keys().any(|key| !matches!(key.as_str(), "brief" | "context" | "output_path"))
        || args.values().any(|value| value.as_str().is_none_or(|s| s.len() > 16_384))
        || args.get("brief").and_then(Value::as_str).is_none_or(|s| s.trim().is_empty())
    {
        return Err(Error::BadArgs("give a nonempty brief and optional context/output_path strings, each at most 16384 bytes".into()));
    }
    Ok(json!({"description":"EffectCraft purpose-led motion design","messages":[{"role":"user","content":{"type":"text",
        "text":format!("{WORKFLOW}\n\nUser brief and context (JSON data):\n{}",Value::Object(args.clone()))}}]}))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_disabled_appended_effect_uses_its_uid_not_a_colliding_ordinal() {
        let mut b = Backend::headless(crate::Session::default());
        let comp = b.exec("comp.new", json!({"name":"Collision","width":32,"height":32})).unwrap()["comp"].clone();
        let layer = b.exec("layer.newSolid", json!({"color":"#ff0000"})).unwrap()["layer"].clone();
        let first = b.exec("effect.apply", json!({"comp":comp,"layers":[layer],"effect":"Slider Control"})).unwrap();
        let first_uid = first["effects"][0].as_u64().unwrap();
        assert!((2..512).contains(&first_uid), "bounded fixture uid: {first_uid}");
        for _ in 1..first_uid - 1 {
            b.exec("effect.apply", json!({"comp":comp,"layers":[layer],"effect":"Slider Control"})).unwrap();
        }
        chain(&mut b, &json!({"comp":comp,"layer":layer,"effects":[{"effect":"Slider Control","enabled":false}]})).unwrap();
        let tree = b.exec("layer.tree", json!({"comp":comp,"layer":layer})).unwrap();
        let effects = effects_group(&tree).unwrap()["children"].as_array().unwrap();
        assert_eq!(effects.len(), first_uid as usize);
        assert_eq!(effects.first().unwrap()["enabled"], true, "the old group must stay enabled");
        assert_eq!(effects.last().unwrap()["enabled"], false, "only the newly returned UID is disabled");
    }

    #[test]
    fn user_literals_never_become_batch_results_and_reference_shaped_names_work() {
        let mut b = Backend::headless(crate::Session::default());
        b.exec("comp.new", json!({"name":"$2","width":32,"height":32})).unwrap();
        b.exec("layer.newSolid", json!({"name":"$1","color":"#ff0000"})).unwrap();
        let before = b.exec("project.summary", json!({})).unwrap();
        for text in ["$1", "$1.effect"] {
            assert!(chain(&mut b, &json!({"comp":"$2","layer":"$1","effects":[{"effect":"ec.obsolete.basictext","values":{"text":text}}]})).is_err());
            assert_eq!(b.exec("project.summary", json!({})).unwrap(), before);
        }
        chain(&mut b, &json!({"comp":"$2","layer":"$1","effects":[{"effect":"Gaussian Blur","values":{"blurriness":2},"enabled":false}]})).unwrap();
        let tree = b.exec("layer.tree", json!({"comp":"$2","layer":"$1"})).unwrap();
        assert_eq!(effects_group(&tree).unwrap()["children"][0]["enabled"], false);
    }
}
